/**
 * FIX-26a 报价单 PDF 永远不印利润率：在 Node 里真的生成旧报价单 PDF，抽出页面文字断言
 *
 * - 用真实的 exportQuotePdf；只把 jsPDF 的 save 换成「把 output() 与文件名存下来」（不写文件、不碰浏览器）
 * - 页面文字 = 内容流里的 `(…) Tj` 文字操作，去掉 `\u0000` 后逐条拼起来：jsPDF 遇到中文时把整句按 UTF-16BE
 *   双字节写进去，同一句里的数字前会夹 `\0`，不去掉就搜不到「65.38」
 * - 只在页面文字里搜具体数值，不在整份 PDF 字节里搜，避免坐标数字碰巧相同
 * - 另有三道兜底（审查 2026-11-23 加，抓 `(…) Tj` 抽取器看不到的泄露）：
 *   1. 整份 PDF 里没有十六进制文字操作 `<…> Tj` 与 `TJ` 数组（嵌入字体时 jsPDF 这样写）；
 *   2. 有利润率 / 利润率为空 / 内部字段全换掉的三份报价单，去掉创建时间、文件 ID 与页脚日期后整份 PDF 逐字节相同、
 *      文件名相同——内部字段不论放进页面、文档属性（Subject / Keywords）还是文件名，都会让三份不一样；
 *   3. 页面文字整页按白名单逐行比对，多一行（白字、拆段、第 2 页、页脚拼数字）少一行都算失败。
 *
 * 运行：npx tsx src/lib/quote/__tests__/export-customer-pdf.test.ts
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { exportQuotePdf } from "../export-pdf";
import type { QuoteTotals } from "../calculate";
import { TEMPLATE_LABELS, type QuoteHeaderData, type QuoteLineItemData } from "../types";

let passed = 0;
let failed = 0;
function ok(name: string, cond: boolean, detail?: unknown) {
  if (cond) { passed++; console.log(`  ✓ ${name}`); }
  else { failed++; console.error(`  ✗ ${name}`, detail !== undefined ? JSON.stringify(detail).slice(0, 800) : ""); }
}

const header: QuoteHeaderData = {
  title: "Window Blinds Supply",
  templateType: "export_standard",
  currency: "CAD",
  tradeTerms: "FOB Shanghai",
  paymentTerms: "T/T 30/70",
  deliveryDays: 45,
  validUntil: "2026-12-31",
  moq: 10,
  originCountry: "China",
  internalNotes: "SECRET-NOTE-7731",
};

const line: QuoteLineItemData = {
  sortOrder: 0,
  category: "product",
  itemName: "Roller Blind 1200",
  specification: "1200x1800",
  unit: "pc",
  quantity: 2,
  unitPrice: 50,
  totalPrice: 100,
  remarks: "INTERNAL-REMARK-5519",
  costPrice: 17.31,
  isInternal: false,
};

const withMargin: QuoteTotals = { subtotal: 100, internalCost: 34.62, totalAmount: 100, profitMargin: 65.38, lineCount: 1 };
const noMargin: QuoteTotals = { ...withMargin, profitMargin: null };
// 第三份：所有内部字段都换成别的值（利润率空、内部成本 0、成本价空、内部备注空、行备注空）
const blankTotals: QuoteTotals = { ...withMargin, internalCost: 0, profitMargin: null };
const blankHeader: QuoteHeaderData = { ...header, internalNotes: "" };
const blankLine: QuoteLineItemData = { ...line, costPrice: null, remarks: "" };

/** 内容流里的 `(…) Tj` 文字操作（jsPDF 默认不压缩内容流），去掉转义，再去掉 UTF-16BE 双字节留下的 \u0000 */
function literals(pdf: string): string[] {
  const out: string[] = [];
  const re = /\(((?:\\.|[^\\)])*)\)\s*Tj/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(pdf))) out.push(m[1].replace(/\\([()\\])/g, "$1").replace(/\u0000/g, ""));
  return out;
}
const pageText = (pdf: string) => literals(pdf).join("\n");

/** jsPDF 对中文按 UTF-16BE 写字节；去掉 \u0000 后与 literals() 抽出来的对得上 */
function utf16beBytesNoNul(s: string): string {
  let out = "";
  for (const ch of s) {
    const c = ch.charCodeAt(0);
    out += String.fromCharCode(c >> 8, c & 0xff);
  }
  return out.replace(/\u0000/g, "");
}

/** 去掉随时间变化的部分：创建时间、文件 ID、页脚日期（长度不变的替换，交叉引用表偏移不受影响） */
function normalize(pdf: string): string {
  return pdf
    .replace(/\/CreationDate \(D:[^)]*\)/g, "/CreationDate (D:X)")
    .replace(/\/ModDate \(D:[^)]*\)/g, "/ModDate (D:X)")
    .replace(/\/ID \[[^\]]*\]/g, "/ID [X]")
    .replace(/Generated by QingYan AI \| \d{4}-\d{2}-\d{2}/g, "Generated by QingYan AI | YYYY-MM-DD");
}

async function render(h: QuoteHeaderData, l: QuoteLineItemData, totals: QuoteTotals): Promise<{ pdf: string; filename: string }> {
  const mod = await import("jspdf");
  const JsPDF = (mod as unknown as { jsPDF?: { API: Record<string, unknown> }; default?: { API: Record<string, unknown> } }).jsPDF ?? mod.default;
  const api = (JsPDF as unknown as { API: Record<string, unknown> }).API;
  const originalSave = api.save;
  let pdf = "";
  let filename = "";
  api.save = function (this: { output: () => string }, name: string) {
    pdf = this.output();
    filename = name;
    return this;
  };
  try {
    await exportQuotePdf({ header: h, lines: [l], totals, projectName: "Demo Project", quoteVersion: 3 });
  } finally {
    api.save = originalSave;
  }
  return { pdf, filename };
}

async function main() {
  console.log("FIX-26a 报价单 PDF 永远不印利润率");

  const a = await render(header, line, withMargin);
  const b = await render(header, line, noMargin);
  const c = await render(blankHeader, blankLine, blankTotals);
  ok("真的生成了 PDF（三份都以 %PDF 开头）", [a, b, c].every((r) => r.pdf.startsWith("%PDF")), [a.pdf.slice(0, 8), b.pdf.slice(0, 8), c.pdf.slice(0, 8)]);

  const textA = pageText(a.pdf);
  const textB = pageText(b.pdf);
  ok("抽得出页面文字", textA.length > 0 && textB.length > 0);

  for (const [label, text] of [["有利润率的报价单", textA], ["利润率为空的报价单", textB]] as const) {
    ok(`${label}：有 QUOTATION、报价标题、项目与版本`, text.includes("QUOTATION") && text.includes("Window Blinds Supply") && text.includes("Project: Demo Project | Version 3"), text);
    ok(`${label}：报价头照常（贸易方式、付款条款、交期、原产地）`, text.includes("FOB Shanghai") && text.includes("T/T 30/70") && text.includes("45 days") && text.includes("China"), text);
    ok(`${label}：行项照常（品名、规格、单价、合计）`, text.includes("Roller Blind 1200") && text.includes("1200x1800") && text.includes("50.00") && text.includes("100.00"), text);
    const totalsBlock = text.slice(text.indexOf("Subtotal:"), text.indexOf("Generated by QingYan AI"));
    ok(`${label}：合计只有 Subtotal 与 Total Amount 两行`, totalsBlock === "Subtotal:\nCAD 100.00\nTotal Amount:\nCAD 100.00\n", totalsBlock);
    ok(`${label}：页脚照常`, /Generated by QingYan AI \| \d{4}-\d{2}-\d{2}/.test(text), text.slice(-60));
    ok(`${label}：去掉 \\u0000 后的页面文字里没有利润率（Margin / 65.38 / %）`, !/margin/i.test(text) && !text.includes("65.38") && !text.includes("%"), text);
    ok(`${label}：没有内部成本 34.62`, !text.includes("34.62"), text);
    ok(`${label}：没有成本价 17.31`, !text.includes("17.31"), text);
    ok(`${label}：没有内部备注`, !text.includes("SECRET-NOTE-7731"), text);
    ok(`${label}：没有行备注`, !text.includes("INTERNAL-REMARK-5519"), text);
  }

  // 兜底 1：抽取器只认 `(…) Tj`；嵌入字体时 jsPDF 写十六进制 `<…> Tj` 或 TJ 数组——整份 PDF 里都不该有
  ok("整份 PDF 里没有十六进制文字操作 <…> Tj 与 TJ 数组", [a, b, c].every((r) => !/<[0-9A-Fa-f\s]+>\s*Tj/.test(r.pdf) && !/\]\s*TJ/.test(r.pdf)));

  // 兜底 2：内部字段换掉，整份 PDF（含文档属性）与文件名都不变
  const na = normalize(a.pdf);
  ok("有利润率与利润率为空：去掉时间戳后整份 PDF 逐字节相同", na === normalize(b.pdf), [na.length, normalize(b.pdf).length]);
  ok("内部字段全换掉（内部成本、成本价、内部备注、行备注、利润率）：去掉时间戳后整份 PDF 逐字节相同", na === normalize(c.pdf), [na.length, normalize(c.pdf).length]);
  ok("三份文件名相同，就是「报价标题_v版本.pdf」", a.filename === "Window Blinds Supply_v3.pdf" && b.filename === a.filename && c.filename === a.filename, [a.filename, b.filename, c.filename]);
  ok("文档属性里没有 Subject 与 Keywords", !/\/Subject\s*\(/.test(a.pdf) && !/\/Keywords\s*\(/.test(a.pdf), a.pdf.slice(a.pdf.indexOf("/Producer") - 20, a.pdf.indexOf("/Producer") + 120));

  // 兜底 3：整页白名单（规格列出的内容，按版式顺序；Template 一栏是中文模板名的 UTF-16BE 字节）
  const expected = [
    "QUOTATION",
    "Window Blinds Supply",
    "Project: Demo Project | Version 3",
    "Template:", utf16beBytesNoNul(TEMPLATE_LABELS.export_standard),
    "Currency:", "CAD",
    "Trade Terms:", "FOB Shanghai",
    "Payment Terms:", "T/T 30/70",
    "Delivery:", "45 days",
    "Valid Until:", "2026-12-31",
    "MOQ:", "10",
    "Origin:", "China",
    "#", "Category", "Item", "Spec", "Unit", "Qty", "Unit Price", "Total",
    "1", "Product", "Roller Blind 1200", "1200x1800", "pc", "2", "50.00", "100.00",
    "Subtotal:", "CAD 100.00",
    "Total Amount:", "CAD 100.00",
    "Generated by QingYan AI | YYYY-MM-DD",
  ];
  const actualA = literals(a.pdf).map((s) => s.replace(/Generated by QingYan AI \| \d{4}-\d{2}-\d{2}/, "Generated by QingYan AI | YYYY-MM-DD"));
  const firstDiff = expected.findIndex((e, i) => actualA[i] !== e);
  ok("整页文字按白名单逐行相同（不多不少）", actualA.length === expected.length && firstDiff === -1, { firstDiff, expected: expected[firstDiff], actual: actualA[firstDiff], expectedLen: expected.length, actualLen: actualA.length });

  const src = readFileSync(join(process.cwd(), "src/lib/quote/export-pdf.ts"), "utf8");
  for (const field of ["profitMargin", "internalCost", "costPrice", "internalNotes"]) {
    ok(`源码断言：export-pdf.ts 不读 ${field}`, !src.includes(field));
  }

  console.log(`\nFIX-26a 报价单 PDF: ${passed} passed, ${failed} failed`);
  if (failed > 0) process.exit(1);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
